"""Strangler-fig gateway core.

AUTO-GENERATED by agents/routing_agent.py. The route table (routes.yaml) maps
URL prefixes to backends; unmatched paths fall through to the monolith. The
proxy forwards each request to the resolved backend through an async "sender".
In production every sender is an ``httpx.AsyncClient`` pointed at a real URL; in
tests, senders wrap the in-process apps (ASGI for the new service, a threaded
WSGI shim for the Flask monolith) so the whole topology runs without Docker.
"""
from __future__ import annotations

import os
from contextlib import asynccontextmanager
from pathlib import Path

import httpx
import yaml
from fastapi import FastAPI, Request, Response

CONFIG_PATH = Path(__file__).with_name("routes.yaml")


def load_route_table(path: Path = CONFIG_PATH) -> dict:
    table = yaml.safe_load(path.read_text())
    defaults = {"MONOLITH_URL": "http://monolith:8000"}
    for name, url in list(table.get("backends", {}).items()):
        if isinstance(url, str) and url.startswith("${") and url.endswith("}"):
            env = url[2:-1]
            table["backends"][name] = os.environ.get(
                env, defaults.get(env, "http://" + name + ":8000")
            )
    return table


def resolve_backend(path: str, table: dict) -> str:
    """First matching prefix wins (longest prefix first); else the default."""
    for route in sorted(table.get("routes", []), key=lambda r: -len(r["prefix"])):
        prefix = route["prefix"]
        if path == prefix or path.startswith(prefix + "/"):
            return route["backend"]
    return table.get("default_backend", "monolith")


def build_gateway_app(table: dict | None = None, senders: dict | None = None) -> FastAPI:
    """Build the gateway. ``senders`` maps backend-name -> an object with an
    async ``request(method, url, params, content, headers) -> httpx.Response``.
    When None, one ``httpx.AsyncClient`` per backend is built from the table."""
    table = table or load_route_table()
    owns = senders is None
    if senders is None:
        senders = {
            name: httpx.AsyncClient(base_url=url, timeout=10.0)
            for name, url in table["backends"].items()
        }

    @asynccontextmanager
    async def lifespan(app):
        yield
        if owns:
            for s in senders.values():
                await s.aclose()

    app = FastAPI(title="Strangler Gateway", lifespan=lifespan)

    @app.get("/__gateway/health")
    def gateway_health() -> dict:
        return {"status": "ok", "service": "gateway", "routes": table["routes"],
                "backends": list(table["backends"])}

    @app.api_route("/{full_path:path}",
                   methods=["GET", "POST", "PUT", "PATCH", "DELETE"])
    async def proxy(full_path: str, request: Request) -> Response:
        path = "/" + full_path
        backend = resolve_backend(path, table)
        body = await request.body()
        upstream = await senders[backend].request(
            request.method, path,
            params=dict(request.query_params),
            content=body,
            headers={k: v for k, v in request.headers.items()
                     if k.lower() not in {"host", "content-length"}},
        )
        headers = {"X-Gateway-Backend": backend}
        if "x-served-by" in upstream.headers:
            headers["X-Served-By"] = upstream.headers["x-served-by"]
        return Response(content=upstream.content, status_code=upstream.status_code,
                        headers=headers,
                        media_type=upstream.headers.get("content-type"))

    return app
